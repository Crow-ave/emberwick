// Emberwick HTTP security check: a player id alone cannot act for that player.
// Starts a throwaway server (no NEAR, no AI, its own save file) and tries the attacks a reviewer would try.
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'emberwick-http-'));
const PORT = 30000 + Math.floor(Math.random() * 20000);
const env = { ...process.env, PORT: String(PORT), EMBERWICK_SAVE: path.join(dir, 'state.json'), EMBERWICK_KEYS: path.join(dir, 'none.json'), EMBERWICK_NEAR: 'off', EMBERWICK_AI: '0', NEARAI_API_KEY: '' };
fs.writeFileSync(path.join(dir, 'ai-proofs.json'), JSON.stringify([{ ok: true, chatId: 'chat-kept', request: '{}', response: '{}' }])); // a proof from before a restart
const srv = spawn(process.execPath, [path.join(here, 'index.js')], { env, stdio: ['ignore', 'pipe', 'pipe'] });
let fails = 0;
const check = (ok, what) => { console.log(`  ${ok ? 'ok  ' : 'FAIL'} ${what}`); if (!ok) fails++; };
const post = async (p, body) => { const r = await fetch(`http://127.0.0.1:${PORT}${p}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) }); return { status: r.status, j: await r.json().catch(() => ({})) }; };
try {
  for (let i = 0; i < 50; i++) { try { await fetch(`http://127.0.0.1:${PORT}/api/world`); break; } catch { await new Promise((r) => setTimeout(r, 200)); } }
  console.log('== NEAR AI proofs');
  const pr = await fetch(`http://127.0.0.1:${PORT}/api/ai/proof`);
  check(pr.status === 200 && (await pr.json()).chatId === 'chat-kept', 'signed answers kept from before a restart are still served');
  const old = await fetch(`http://127.0.0.1:${PORT}/api/ai/proof?chat=nope`);
  check(old.status === 404, 'an unknown answer gives a clear 404');
  const dh = await fetch(`http://127.0.0.1:${PORT}/api/deed/holder?plot=plot-1`);
  check(dh.status === 200 && (await dh.json()).ok === false, 'the live deed-holder check answers calmly when there is no deed or no NEAR');
  console.log('== player keys');
  const a = await post('/api/join', { name: 'Alice', path: 'miner' });
  check(a.j.ok && typeof a.j.key === 'string' && a.j.key.length >= 32, 'joining returns a long random key');
  const b = await post('/api/join', { name: 'Mallory', path: 'miner' });
  const pid = a.j.id;
  const noKey = await post('/api/action', { player: pid, action: { type: 'gather', spot: 'mine' } });
  check(noKey.status === 403 && noKey.j.code === 'err.notYou', 'acting for a player with only their id is refused');
  const wrong = await post('/api/action', { player: pid, key: b.j.key, action: { type: 'gather', spot: 'mine' } });
  check(wrong.status === 403, "acting for a player with someone else's key is refused");
  const link = await post('/api/near/link', { player: pid, key: b.j.key, account: 'mallory.testnet' });
  check(link.status === 403, 'linking a wallet to someone else is refused');
  const out = await post('/api/near/withdraw', { player: pid, key: b.j.key, amount: 5 });
  check(out.status === 403, "cashing out someone else's coins is refused");
  const own = await post('/api/action', { player: pid, key: a.j.key, action: { type: 'gather', spot: 'mine' } });
  check(own.status !== 403, 'the player with their own key can act');
  const claim = await post('/api/claim', { player: pid });
  check(claim.status === 403 && !claim.j.key, 'a player who has a key cannot be claimed again');
  const v1 = await post('/api/near/link', { player: pid, key: a.j.key, account: 'alice.testnet' });
  check(v1.status === 200, 'a player can link a wallet with their own key');
  console.log('== sign in with a wallet (EVM, Solana)');
  const { secp256k1 } = await import('@noble/curves/secp256k1.js'); const { keccak_256 } = await import('@noble/hashes/sha3.js'); const { ed25519 } = await import('@noble/curves/ed25519.js');
  const B58 = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
  const b58 = (b) => { let n = BigInt('0x' + Buffer.from(b).toString('hex')), s = ''; while (n > 0n) { s = B58[Number(n % 58n)] + s; n /= 58n; } for (const x of b) { if (x) break; s = '1' + s; } return s; };
  const evmKey = secp256k1.utils.randomSecretKey(), evmAddr = '0x' + Buffer.from(keccak_256(secp256k1.getPublicKey(evmKey, false).subarray(1)).subarray(-20)).toString('hex');
  const evmSign = (msg) => { const m = new TextEncoder().encode(msg), pre = new TextEncoder().encode('\x19Ethereum Signed Message:\n' + m.length); const r = Buffer.from(secp256k1.sign(keccak_256(new Uint8Array([...pre, ...m])), evmKey, { prehash: false, format: 'recovered' })); return '0x' + Buffer.concat([r.subarray(1), Buffer.from([r[0] + 27])]).toString('hex'); };
  const solKey = ed25519.utils.randomSecretKey(), solAddr = b58(ed25519.getPublicKey(solKey));
  const solSign = (msg) => Buffer.from(ed25519.sign(new TextEncoder().encode(msg), solKey)).toString('base64');
  const chal = async (q) => (await fetch(`http://127.0.0.1:${PORT}/api/signin/challenge?${new URLSearchParams(q)}`)).json();
  let c = await chal({ chain: 'evm', address: evmAddr, purpose: 'link', player: pid });
  check(c.ok && c.message.includes(evmAddr) && c.message.includes(c.nonce), 'the message names the wallet and a fresh nonce');
  const lk = await post('/api/signin/link', { player: pid, key: a.j.key, nonce: c.nonce, signature: evmSign(c.message) });
  check(lk.status === 200 && lk.j.logins.some((l) => l.chain === 'evm'), 'Alice links her MetaMask wallet');
  const again = await post('/api/signin/link', { player: pid, key: a.j.key, nonce: c.nonce, signature: evmSign(c.message) });
  check(again.status === 400, 'a signed message cannot be used twice');
  c = await chal({ chain: 'evm', address: evmAddr, purpose: 'link', player: b.j.id });
  const steal = await post('/api/signin/link', { player: b.j.id, key: b.j.key, nonce: c.nonce, signature: evmSign(c.message) });
  check(steal.status === 400 && steal.j.code === 'err.walletUsed', 'the same wallet cannot sign in as two villagers');
  c = await chal({ chain: 'evm', address: evmAddr, purpose: 'login' });
  const forged = await post('/api/signin/login', { nonce: c.nonce, signature: evmSign('something else') });
  check(forged.status === 400 && !forged.j.key, 'a signature over another message is refused');
  c = await chal({ chain: 'evm', address: evmAddr, purpose: 'login' });
  const li = await post('/api/signin/login', { nonce: c.nonce, signature: evmSign(c.message) });
  check(li.status === 200 && li.j.id === pid && li.j.key && li.j.key !== a.j.key, 'on another device, the wallet brings Alice back with a new key');
  const dev2 = await post('/api/action', { player: pid, key: li.j.key, action: { type: 'gather', spot: 'mine' } });
  const dev1 = await post('/api/action', { player: pid, key: a.j.key, action: { type: 'gather', spot: 'mine' } });
  check(dev2.status !== 403 && dev1.status !== 403, 'both devices stay signed in');
  c = await chal({ chain: 'sol', address: solAddr, purpose: 'link', player: b.j.id });
  const sl1 = await post('/api/signin/link', { player: b.j.id, key: b.j.key, nonce: c.nonce, signature: solSign(c.message) });
  check(sl1.status === 200, 'Mallory links her Phantom (Solana) wallet');
  c = await chal({ chain: 'sol', address: solAddr, purpose: 'login' });
  const sl2 = await post('/api/signin/login', { nonce: c.nonce, signature: solSign(c.message) });
  check(sl2.status === 200 && sl2.j.id === b.j.id, 'and signs in with it');
  const other = ed25519.utils.randomSecretKey(), otherAddr = b58(ed25519.getPublicKey(other));
  c = await chal({ chain: 'sol', address: otherAddr, purpose: 'login' });
  const nobody = await post('/api/signin/login', { nonce: c.nonce, signature: Buffer.from(ed25519.sign(new TextEncoder().encode(c.message), other)).toString('base64') });
  check(nobody.status === 404 && nobody.j.code === 'err.noVillager', 'a wallet with no villager gets a clear answer');
  c = await chal({ chain: 'sol', address: solAddr, purpose: 'login' });
  const wrongKey = await post('/api/signin/login', { nonce: c.nonce, signature: Buffer.from(ed25519.sign(new TextEncoder().encode(c.message), other)).toString('base64') });
  check(wrongKey.status === 400, "signing with another wallet's key is refused");
  const bad = await chal({ chain: 'evm', address: 'not-an-address', purpose: 'login' });
  check(!bad.ok, 'a malformed address is refused');
  const nearOff = await chal({ chain: 'near', address: 'alice.testnet', purpose: 'login' });
  const nearTry = await post('/api/signin/login', { nonce: nearOff.nonce, signature: 'x', publicKey: 'ed25519:x' });
  check(nearTry.status === 400 && nearTry.j.code === 'err.chainOff', 'NEAR sign-in waits for NEAR when it is off');
  const st2 = await (await fetch(`http://127.0.0.1:${PORT}/api/state?player=${b.j.id}`)).json();
  check(!JSON.stringify(st2.others || []).includes(evmAddr) && JSON.stringify(st2.player.logins).includes(solAddr), "a villager's sign-in wallets are shown only to them");
  const sl = []; for (let i = 0; i < 8; i++) sl.push((await post('/api/join', { name: 'Spam' + i, path: 'miner' })).status);
  check(sl.includes(429), 'joining again and again from one address is slowed down (' + sl.join(',') + ')');
  const st = await (await fetch(`http://127.0.0.1:${PORT}/api/state?player=${b.j.id}`)).json();
  check(!JSON.stringify(st).includes(a.j.key) && !JSON.stringify(st).includes('playerKeys'), 'keys never appear in the shared view');
} catch (e) { console.log('  FAIL', e.message); fails++; }
srv.kill();
fs.rmSync(dir, { recursive: true, force: true });
console.log(fails ? `\n${fails} HTTP check(s) failed.` : '\nAll HTTP security checks passed.');
process.exit(fails ? 1 : 0);
